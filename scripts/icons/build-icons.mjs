// Builds trimmed Phosphor icon fonts holding only the icons this app uses (the full fonts are
// ~430 KB plus a ~190 KB stylesheet; the app uses a few hundred icons). Run after adding an icon:
//   PYFTSUBSET=/path/to/pyftsubset node scripts/icons/build-icons.mjs
// (pyftsubset comes from `pip install fonttools brotli`). It writes src/styles/icons/*, which is
// committed, so normal builds need nothing extra. src/styles/icons/__tests__ fails if code uses an
// icon the trimmed set lacks.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const SRC = join(ROOT, "src");
const OUT = join(SRC, "styles/icons");
const PKG = join(ROOT, "node_modules/@phosphor-icons/web/src");
const PYFTSUBSET = process.env.PYFTSUBSET || "pyftsubset";

const WEIGHTS = [
  { dir: "regular", cls: "ph", file: "Phosphor", out: "phosphor-regular" },
  { dir: "bold", cls: "ph-bold", file: "Phosphor-Bold", out: "phosphor-bold" },
  { dir: "fill", cls: "ph-fill", file: "Phosphor-Fill", out: "phosphor-fill" },
];
// Names the code builds at run time (`ph-caret-${open ? "up" : "down"}`).
const DYNAMIC = ["ph-caret-up", "ph-caret-down"];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (p.startsWith(OUT)) continue;
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|css|mjs)$/.test(name)) out.push(p);
  }
  return out;
}
export function usedIconNames() {
  const names = new Set(DYNAMIC);
  for (const f of walk(SRC)) for (const m of readFileSync(f, "utf8").matchAll(/\bph-[a-z0-9]+(?:-[a-z0-9]+)*/g)) names.add(m[0]);
  return names;
}

const used = usedIconNames();
mkdirSync(OUT, { recursive: true });
const report = [];
for (const w of WEIGHTS) {
  const css = readFileSync(join(PKG, w.dir, "style.css"), "utf8");
  const base = css.slice(css.indexOf(`.${w.cls} {`), css.indexOf("}", css.indexOf(`.${w.cls} {`)) + 1);
  const rules = [];
  const codepoints = [];
  const re = new RegExp(`\\.${w.cls.replace("-", "\\-")}\\.(ph-[a-z0-9-]+):before \\{\\s*content: "\\\\([0-9a-f]+)";\\s*\\}`, "g");
  for (const m of css.matchAll(re)) {
    if (!used.has(m[1])) continue;
    rules.push(`.${w.cls}.${m[1]}:before{content:"\\${m[2]}"}`);
    codepoints.push(`U+${m[2]}`);
  }
  execFileSync(PYFTSUBSET, [join(PKG, w.dir, `${w.file}.ttf`), `--unicodes=${codepoints.join(",")}`, "--flavor=woff2", "--layout-features=*", "--no-hinting", `--output-file=${join(OUT, `${w.out}.woff2`)}`]);
  const face = `@font-face{font-family:"${w.file}";src:url("./${w.out}.woff2") format("woff2");font-weight:normal;font-style:normal;font-display:block}`;
  writeFileSync(join(OUT, `${w.out}.css`), `/* Generated by scripts/icons/build-icons.mjs: only the icons the app uses. */\n${face}\n${base}\n${rules.join("\n")}\n`);
  report.push(`${w.dir}: ${rules.length} icons, ${Math.round(statSync(join(OUT, `${w.out}.woff2`)).size / 1024)} KB`);
}
writeFileSync(join(OUT, "used-icons.json"), JSON.stringify([...used].sort(), null, 0) + "\n");
console.log(report.join("\n"));
